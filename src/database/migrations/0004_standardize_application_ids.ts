async function columnDataType(
  client: PoolClient,
  tableName: string,
  columnName: string,
): Promise<string | null> {
  const result = await client.query<{ data_type: string }>(
    `SELECT data_type
     FROM information_schema.columns
     WHERE table_schema = 'public'
       AND table_name = $1
       AND column_name = $2`,
    [tableName, columnName],
  );
  return result.rows[0]?.data_type ?? null;
}

async function convertConversationsAndForeignKeys(
  client: PoolClient,
): Promise<void> {
  await client.query(`
    ALTER TABLE conversations
      ADD COLUMN id_new BIGINT GENERATED BY DEFAULT AS IDENTITY;
  `);

  await client.query(`
    ALTER TABLE messages
      ADD COLUMN conversation_id_new BIGINT;
  `);

  await client.query(`
    UPDATE messages AS m
    SET conversation_id_new = c.id_new
    FROM conversations AS c
    WHERE m.conversation_id = c.id;
  `);

  const orphanCount = await client.query<{ count: string }>(
    `SELECT COUNT(*)::text AS count
     FROM messages
     WHERE conversation_id_new IS NULL`,
  );
  if (Number(orphanCount.rows[0]?.count ?? "0") > 0) {
    throw new Error(
      "Migration 0004: found messages without a mapped conversation_id_new; aborting.",
    );
  }

  await client.query(`
    ALTER TABLE messages
      DROP CONSTRAINT IF EXISTS messages_conversation_id_fkey;
  `);

  await client.query(`
    ALTER TABLE messages
      DROP COLUMN conversation_id;
  `);

  await client.query(`
    ALTER TABLE messages
      RENAME COLUMN conversation_id_new TO conversation_id;
  `);

  await client.query(`
    ALTER TABLE messages
      ALTER COLUMN conversation_id SET NOT NULL;
  `);

  await client.query(`
    ALTER TABLE conversations
      DROP CONSTRAINT conversations_pkey;
  `);

  await client.query(`
    ALTER TABLE conversations
      DROP COLUMN id;
  `);

  await client.query(`
    ALTER TABLE conversations
      RENAME COLUMN id_new TO id;
  `);

  await client.query(`
    ALTER TABLE conversations
      ADD PRIMARY KEY (id);
  `);

  // Column already has an identity sequence from id_new; prefer ALWAYS inserts.
  await client.query(`
    ALTER TABLE conversations
      ALTER COLUMN id SET GENERATED ALWAYS;
  `);

  await client.query(`
    ALTER TABLE messages
      ADD CONSTRAINT messages_conversation_id_fkey
      FOREIGN KEY (conversation_id) REFERENCES conversations(id) ON DELETE CASCADE;
  `);
}

async function convertMessagePrimaryKeys(client: PoolClient): Promise<void> {
  const messageIdType = await columnDataType(client, "messages", "id");
  if (messageIdType === "bigint") {
    return;
  }
  if (messageIdType !== "uuid") {
    throw new Error(
      `Migration 0004: unsupported messages.id type "${messageIdType}" during conversion.`,
    );
  }

  await client.query(`
    ALTER TABLE messages
      ADD COLUMN id_new BIGINT GENERATED BY DEFAULT AS IDENTITY;
  `);

  await client.query(`
    ALTER TABLE messages
      DROP CONSTRAINT messages_pkey;
  `);

  await client.query(`
    ALTER TABLE messages
      DROP COLUMN id;
  `);

  await client.query(`
    ALTER TABLE messages
      RENAME COLUMN id_new TO id;
  `);

  await client.query(`
    ALTER TABLE messages
      ADD PRIMARY KEY (id);
  `);

  await client.query(`
    ALTER TABLE messages
      ALTER COLUMN id SET GENERATED ALWAYS;
  `);
}

